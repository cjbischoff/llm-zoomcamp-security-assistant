"""EVALUATION.md section-heading contract (EVL-04, D-11).

Skips cleanly when ``evaluation/EVALUATION.md`` is absent so the offline suite
stays green before the live run produces the report; once the report exists it
asserts every required section heading is present. No network, no imports of the
live eval surface — a pure file assertion.
"""

import os

import pytest

REPORT_PATH = "evaluation/EVALUATION.md"

REQUIRED_HEADINGS = (
    "## Methodology",
    "## Ground Truth",
    "## Retrieval Metrics",
    "## Chosen Production Mode",
    "## LLM-as-Judge",
    "## Human Spot-Check",
)


def test_report_has_required_sections():
    """EVALUATION.md contains every required heading (skips if not yet generated)."""
    if not os.path.exists(REPORT_PATH):
        pytest.skip(f"{REPORT_PATH} absent — generated by the live run (Plan 04-04 checkpoint)")

    with open(REPORT_PATH) as f:
        content = f.read()

    missing = [h for h in REQUIRED_HEADINGS if h not in content]
    assert not missing, f"EVALUATION.md missing required headings: {missing}"
